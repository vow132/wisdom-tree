import { readFile, writeFile } from 'node:fs/promises';

const models = JSON.parse(await readFile(new URL('../backend/data/default-models.json', import.meta.url), 'utf8'));
const target = new URL('../backend/migrations/008_default_models.sql', import.meta.url);
const ids = new Set();
const sourceIds = new Set();
const validId = value => typeof value === 'string' && /^[a-zA-Z0-9][a-zA-Z0-9._-]{0,99}$/.test(value);
const integer = (value, min, max) => Number.isInteger(value) && value >= min && value <= max;
if (!Array.isArray(models) || models.length !== 3) throw new Error('Expected three public default models.');
for (const model of models) {
  if (!validId(model.id) || !validId(model.sourceId) || ids.has(model.id) || sourceIds.has(model.sourceId)
    || model.id === 'wisdom-tree' || model.sourceId === 'wisdom-tree'
    || typeof model.displayName !== 'string' || !model.displayName.trim() || model.displayName.length > 100
    || !integer(model.coinsPerCall, 0, 2147483647) || typeof model.enabled !== 'boolean'
    || !integer(model.streamChunkChars, 1, 1000) || !integer(model.streamDelayMs, 0, 1000)) {
    throw new Error('Invalid public default model metadata.');
  }
  ids.add(model.id);
  sourceIds.add(model.sourceId);
}
const literal = value => "'" + value.replaceAll("'", "''") + "'";
const updates = models.map(model => `  UPDATE models SET id=${literal(model.id)},display_name=${literal(model.displayName)},
    coins_per_call=${model.coinsPerCall},enabled=${model.enabled},
    stream_chunk_chars=${model.streamChunkChars},stream_delay_ms=${model.streamDelayMs},updated_at=now()
  WHERE id=${literal(model.sourceId)} AND NOT is_wisdom_tree AND deleted_at IS NULL;`).join('\n');
const migration = `-- Generated by scripts/generate-default-model-migration.mjs from public seed data.
-- Fresh installations inherit the owner's public model configuration. Existing
-- installations with any accounts keep administrator names, IDs and pricing.
-- Earlier migrations are immutable; model relations use ON UPDATE CASCADE.
DO $default_models$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM users) THEN
${updates}
  END IF;
END;
$default_models$;
`;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== migration) throw new Error('Default model migration is out of date; run node scripts/generate-default-model-migration.mjs.');
  console.log('Public model metadata and migration agree.');
} else {
  await writeFile(target, migration);
  console.log('Generated 008_default_models.sql.');
}
