import { readFile, writeFile } from 'node:fs/promises';

const reply = await readFile(new URL('../backend/data/default-model-reply.txt', import.meta.url), 'utf8');
const target = new URL('../backend/migrations/007_default_model_reply.sql', import.meta.url);
if (!reply.trim() || reply.length > 20000 || reply.includes('$default_reply$') || reply.includes('\r')) throw new Error('Invalid default model reply.');
const literal = '$default_reply$' + reply + '$default_reply$';
const migration = `-- Generated by scripts/generate-default-reply-migration.mjs from public seed data.
-- Upgrade only untouched placeholders; administrator edits and accepted request
-- snapshots remain intact. The wisdom model is identified by its stable marker.
UPDATE model_replies r SET text=${literal},updated_at=now()
WHERE r.text='智慧树说：每天照料一点，耐心就会发芽。'
  AND EXISTS(SELECT 1 FROM models m WHERE m.id=r.model_id
    AND NOT m.is_wisdom_tree AND m.deleted_at IS NULL
    AND m.reply_text='智慧树说：每天照料一点，耐心就会发芽。');
UPDATE models SET reply_text=${literal},updated_at=now()
WHERE NOT is_wisdom_tree AND deleted_at IS NULL
  AND reply_text='智慧树说：每天照料一点，耐心就会发芽。';
`;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== migration) throw new Error('Default reply migration is out of date; run node scripts/generate-default-reply-migration.mjs.');
  console.log('Default reply seed and migration agree.');
} else {
  await writeFile(target, migration);
  console.log('Generated 007_default_model_reply.sql.');
}
